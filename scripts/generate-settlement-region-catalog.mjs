import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';

const ROOT = process.cwd();
const SETTLEMENTS_PATH = path.join(ROOT, 'src', 'data', 'settlements.ts');
const SUPPLEMENT_PATH = path.join(ROOT, 'src', 'data', 'settlementSupplement.ts');
const DISTRICT_LOOKUP_PATH = path.join(
  ROOT,
  'src',
  'data',
  'settlementDistrictLookup.ts'
);
const OUTPUT_DIR = path.join(ROOT, 'src', 'data', 'settlementCatalogRegions');
const DISTRICT_SOURCE_REGIONS_PATH = path.join(
  ROOT,
  'src',
  'data',
  'districtSourceRegions.ts'
);

const REGION_ORDER = [
  'center',
  'haifa',
  'jerusalem',
  'judea_samaria',
  'north',
  'shephelah',
  'south',
  'tel_aviv',
];

function extractLiteral(source, exportName, openChar, closeChar) {
  const exportIndex = source.indexOf(`export const ${exportName}`);

  if (exportIndex === -1) {
    throw new Error(`Could not find export ${exportName}.`);
  }

  const equalsIndex = source.indexOf('=', exportIndex);
  const startIndex = source.indexOf(openChar, equalsIndex);

  if (startIndex === -1) {
    throw new Error(`Could not find ${openChar} for ${exportName}.`);
  }

  let depth = 0;
  let inString = false;
  let stringQuote = '';
  let escaped = false;

  for (let index = startIndex; index < source.length; index += 1) {
    const char = source[index];

    if (inString) {
      if (escaped) {
        escaped = false;
        continue;
      }

      if (char === '\\') {
        escaped = true;
        continue;
      }

      if (char === stringQuote) {
        inString = false;
        stringQuote = '';
      }

      continue;
    }

    if (char === '"' || char === "'" || char === '`') {
      inString = true;
      stringQuote = char;
      continue;
    }

    if (char === openChar) {
      depth += 1;
      continue;
    }

    if (char === closeChar) {
      depth -= 1;

      if (depth === 0) {
        return source.slice(startIndex, index + 1);
      }
    }
  }

  throw new Error(`Could not extract literal for ${exportName}.`);
}

function evaluateLiteral(literalSource) {
  return vm.runInNewContext(`(${literalSource})`, {});
}

async function main() {
  const [settlementsSource, supplementSource, districtLookupSource] = await Promise.all([
    fs.readFile(SETTLEMENTS_PATH, 'utf8'),
    fs.readFile(SUPPLEMENT_PATH, 'utf8'),
    fs.readFile(DISTRICT_LOOKUP_PATH, 'utf8'),
  ]);

  const baseSettlements = evaluateLiteral(
    extractLiteral(settlementsSource, 'baseSettlements', '[', ']')
  );
  const settlementAliasOverrides = evaluateLiteral(
    extractLiteral(supplementSource, 'settlementAliasOverrides', '{', '}')
  );
  const supplementalSettlements = evaluateLiteral(
    extractLiteral(supplementSource, 'supplementalSettlements', '[', ']')
  );
  const settlementDistrictById = evaluateLiteral(
    extractLiteral(districtLookupSource, 'settlementDistrictById', '{', '}')
  );

  const settlements = [
    ...baseSettlements.map((settlement) => {
      const aliases = settlementAliasOverrides[settlement.id];

      if (!aliases?.length) {
        return settlement;
      }

      return {
        ...settlement,
        aliases: [...new Set([...(settlement.aliases ?? []), ...aliases])],
      };
    }),
    ...supplementalSettlements,
  ];

  const settlementsByRegion = new Map();

  for (const settlement of settlements) {
    const regionSettlements = settlementsByRegion.get(settlement.region) ?? [];
    regionSettlements.push(settlement);
    settlementsByRegion.set(settlement.region, regionSettlements);
  }

  const regionIds = [...settlementsByRegion.keys()].sort((left, right) => {
    const leftIndex = REGION_ORDER.indexOf(left);
    const rightIndex = REGION_ORDER.indexOf(right);

    if (leftIndex === -1 && rightIndex === -1) {
      return left.localeCompare(right);
    }

    if (leftIndex === -1) {
      return 1;
    }

    if (rightIndex === -1) {
      return -1;
    }

    return leftIndex - rightIndex;
  });

  await fs.rm(OUTPUT_DIR, { recursive: true, force: true });
  await fs.mkdir(OUTPUT_DIR, { recursive: true });

  await Promise.all(
    regionIds.map(async (regionId) => {
      const regionSettlements = settlementsByRegion.get(regionId) ?? [];
      const fileContents = [
        "import type { Settlement } from '../../types';",
        '',
        '// Generated by `npm run settlements:generate-regions`.',
        `export const settlements: Settlement[] = ${JSON.stringify(regionSettlements, null, 2)};`,
        '',
      ].join('\n');

      await fs.writeFile(
        path.join(OUTPUT_DIR, `${regionId}.ts`),
        fileContents,
        'utf8'
      );
    })
  );

  const loaderContents = [
    '// Generated by `npm run settlements:generate-regions`.',
    'export const settlementRegionLoaders = {',
    ...regionIds.map(
      (regionId) => `  ${regionId}: () => import('./${regionId}.ts'),`
    ),
    '} as const;',
    '',
    'export type SettlementRegionId = keyof typeof settlementRegionLoaders;',
    '',
  ].join('\n');

  await fs.writeFile(path.join(OUTPUT_DIR, 'loaders.ts'), loaderContents, 'utf8');

  const districtSourceRegions = {};

  for (const settlement of settlements) {
    const districtId = settlementDistrictById[settlement.id];

    if (!districtId) {
      continue;
    }

    const sourceRegions = districtSourceRegions[districtId] ?? new Set();
    sourceRegions.add(settlement.region);
    districtSourceRegions[districtId] = sourceRegions;
  }

  const normalizedDistrictSourceRegions = Object.fromEntries(
    Object.entries(districtSourceRegions)
      .sort(([left], [right]) => left.localeCompare(right, 'he'))
      .map(([districtId, sourceRegions]) => [
        districtId,
        [...sourceRegions].sort((left, right) => left.localeCompare(right)),
      ])
  );

  const districtSourceRegionContents = [
    "import type { SettlementRegionId } from './settlementCatalogRegions/loaders';",
    '',
    '// Generated by `npm run settlements:generate-regions`.',
    `export const districtSourceRegions: Record<string, SettlementRegionId[]> = ${JSON.stringify(
      normalizedDistrictSourceRegions,
      null,
      2
    )};`,
    '',
  ].join('\n');

  await fs.writeFile(
    DISTRICT_SOURCE_REGIONS_PATH,
    districtSourceRegionContents,
    'utf8'
  );

  console.log(
    `Generated ${regionIds.length} settlement region chunks from ${settlements.length} settlements.`
  );
}

await main();
