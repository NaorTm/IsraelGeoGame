import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const BOUNDARIES_DIR = path.join(ROOT, 'src', 'data', 'boundaries');
const DISTRICT_LOADERS_PATH = path.join(BOUNDARIES_DIR, 'byDistrict', 'loaders.ts');
const REGION_LOADERS_PATH = path.join(BOUNDARIES_DIR, 'loaders.ts');
const OUTPUT_PATH = path.join(BOUNDARIES_DIR, 'loadMetadata.ts');

function parseLoaderEntries(source) {
  return [...source.matchAll(/"([^"]+)": \(\) => import\('\.\/([^']+)'\)/g)].map(
    ([, id, fileName]) => ({
      id,
      fileName: fileName.endsWith('.ts') ? fileName : `${fileName}.ts`,
    })
  );
}

function formatRecordLines(entries) {
  return entries.map(
    ({ id, bytes }) => `  ${JSON.stringify(id)}: ${bytes},`
  );
}

async function buildMetadata() {
  const districtLoadersSource = await fs.readFile(DISTRICT_LOADERS_PATH, 'utf8');
  const regionLoadersSource = await fs.readFile(REGION_LOADERS_PATH, 'utf8');

  const districtEntries = await Promise.all(
    parseLoaderEntries(districtLoadersSource).map(async ({ id, fileName }) => ({
      id,
      bytes: (await fs.stat(path.join(BOUNDARIES_DIR, 'byDistrict', fileName))).size,
    }))
  );

  const regionEntries = await Promise.all(
    parseLoaderEntries(regionLoadersSource).map(async ({ id, fileName }) => ({
      id,
      bytes: (await fs.stat(path.join(BOUNDARIES_DIR, fileName))).size,
    }))
  );

  const kmlSupplementEstimatedBytes = (
    await fs.stat(path.join(BOUNDARIES_DIR, 'kmlSupplement.ts'))
  ).size;

  const output = [
    "import type { BoundaryDistrictId } from './byDistrict/loaders';",
    "import type { BoundaryRegionId } from './loaders';",
    '',
    '// Generated by `npm run boundaries:generate-load-metadata`.',
    'export const boundaryDistrictEstimatedBytes: Record<BoundaryDistrictId, number> = {',
    ...formatRecordLines(districtEntries),
    '};',
    '',
    '// Generated by `npm run boundaries:generate-load-metadata`.',
    'export const boundaryRegionEstimatedBytes: Record<BoundaryRegionId, number> = {',
    ...formatRecordLines(regionEntries),
    '};',
    '',
    '// Generated by `npm run boundaries:generate-load-metadata`.',
    `export const kmlSupplementEstimatedBytes = ${kmlSupplementEstimatedBytes};`,
    '',
  ].join('\n');

  await fs.writeFile(OUTPUT_PATH, output, 'utf8');
  console.log(
    `Generated boundary load metadata for ${districtEntries.length} districts and ${regionEntries.length} regions.`
  );
}

await buildMetadata();
