import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

const projectRoot = process.cwd();

async function loadTsModule(relativePath) {
  const absolutePath = path.join(projectRoot, relativePath);
  const source = await fs.readFile(absolutePath, 'utf8');
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.ES2020,
    },
  }).outputText;

  const tempDir = await fs.mkdtemp(path.join(os.tmpdir(), 'igg-seed-'));
  const tempFile = path.join(tempDir, path.basename(relativePath).replace(/\.ts$/, '.mjs'));
  await fs.writeFile(tempFile, transpiled, 'utf8');

  try {
    return await import(`${pathToFileURL(tempFile).href}?t=${Date.now()}`);
  } finally {
    await fs.rm(tempDir, { recursive: true, force: true });
  }
}

function sqlString(value) {
  return `'${String(value ?? '').replace(/'/g, "''")}'`;
}

function districtNameEn(value) {
  return value.name_en || value.name_he;
}

async function main() {
  const [{ settlements }, { regions, districtSettlementIds }, { approximateSettlementIds }] =
    await Promise.all([
      loadTsModule('src/data/settlements.ts'),
      loadTsModule('src/data/districts.ts'),
      loadTsModule('src/data/boundaries/metadata.ts'),
    ]);

  const approximateSet = new Set(approximateSettlementIds);
  const districtBySettlementId = new Map(
    Object.entries(districtSettlementIds).flatMap(([districtId, settlementIds]) =>
      settlementIds.map((settlementId) => [settlementId, districtId])
    )
  );

  const districtRows = [
    ...regions.map((region) => ({
      id: region.id,
      name_he: region.name_he,
      name_en: districtNameEn(region),
    })),
    { id: 'all_israel', name_he: 'כל ישראל', name_en: 'All Israel' },
    { id: 'mixed_regions', name_he: 'מספר מחוזות', name_en: 'Mixed Regions' },
  ];

  const settlementRows = settlements
    .filter((settlement) => !approximateSet.has(settlement.id))
    .map((settlement) => ({
      id: settlement.id,
      district_id: districtBySettlementId.get(settlement.id) ?? settlement.region,
      region_id: settlement.region,
      name_he: settlement.name_he,
      name_en: settlement.name_en,
      lat: settlement.lat,
      lng: settlement.lng,
    }))
    .sort((a, b) => a.id.localeCompare(b.id));

  const lines = [
    '-- Generated by npm run supabase:seed',
    'truncate table public.session_answer_events cascade;',
    'truncate table public.player_round_results cascade;',
    'truncate table public.session_rounds cascade;',
    'truncate table public.session_players cascade;',
    'truncate table public.game_sessions cascade;',
    'truncate table public.matchmaking_queue cascade;',
    'truncate table public.user_district_progress cascade;',
    'truncate table public.settlements_catalog cascade;',
    'truncate table public.districts cascade;',
    '',
    'insert into public.districts (id, name_he, name_en)',
    'values',
    districtRows
      .map((district) => `  (${sqlString(district.id)}, ${sqlString(district.name_he)}, ${sqlString(district.name_en)})`)
      .join(',\n') + ';',
    '',
    'insert into public.settlements_catalog (id, district_id, region_id, name_he, name_en, lat, lng, playable)',
    'values',
    settlementRows
      .map(
        (settlement) =>
          `  (${sqlString(settlement.id)}, ${sqlString(settlement.district_id)}, ${sqlString(settlement.region_id)}, ${sqlString(settlement.name_he)}, ${sqlString(settlement.name_en)}, ${settlement.lat}, ${settlement.lng}, true)`
      )
      .join(',\n') + ';',
    '',
  ];

  await fs.writeFile(path.join(projectRoot, 'supabase', 'seed.sql'), lines.join('\n'), 'utf8');
  console.log(`Wrote supabase/seed.sql with ${districtRows.length} districts and ${settlementRows.length} settlements.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
